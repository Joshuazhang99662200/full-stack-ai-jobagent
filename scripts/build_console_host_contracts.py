"""Generate host transport types from Python schemas, without a second type authority."""

import argparse
import json
from pathlib import Path
from typing import Any

from jobagent.schemas.console_host import (
    HostDecisionRequest,
    HostExecutionRequest,
    HostState,
)

OUTPUT = Path(__file__).resolve().parents[1] / "frontend/src/hostContracts.ts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {"string": "string", "number": "number", "integer": "number",
            "boolean": "boolean", "null": "null"}[kind]


def generate() -> str:
    models = {}
    for model in (HostState, HostDecisionRequest, HostExecutionRequest):
        schema = model.model_json_schema()
        models.update(schema.pop("$defs", {}))
        models[model.__name__] = schema
    lines = ["// Generated by scripts/build_console_host_contracts.py. Do not edit."]
    for name, schema in sorted(models.items()):
        lines.append(f"export interface {name} {{")
        for key, value in schema["properties"].items():
            lines.append(f"  {key}: {ts_type(value)};")
        lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Host transport types are stale; run this script without --check")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
